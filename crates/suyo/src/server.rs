//! HTTP server: Graphite-compatible read API, ingest, dashboards, and the
//! embedded web UI. Each worker thread owns its own SQLite connection.

use crate::render::{self, Params};
use crate::store::{AggFn, MetaHint, Store};
use crate::timeutil::{Span, Zone};
use crate::{catalog, eval, ingest, svg};
use anyhow::{anyhow, Result};
use serde_json::{json, Value};
use std::collections::{BTreeMap, HashMap};
use std::io::Read;
use std::path::PathBuf;
use std::sync::Arc;
use tiny_http::{Header, Method, Request, Response, Server};

pub struct App {
    pub db: String,
    pub zone: Zone,
    pub assets: Option<PathBuf>,
    pub write_token: Option<String>,
    /// Path prefix when mounted inside another server, e.g. "/suyo"; empty when standalone.
    pub base: String,
    /// Host branding when embedded: (name, home link) and extra top-bar links (label, href).
    pub brand: Option<(String, String)>,
    pub nav: Vec<(String, String)>,
}

// Built UI files (ui/dist), generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/ui_assets.rs"));

fn embedded(name: &str) -> Option<(&'static str, &'static [u8])> {
    UI_FILES
        .iter()
        .find(|(n, _, _)| *n == name)
        .map(|(_, ct, b)| (*ct, *b))
}

fn content_type(name: &str) -> &'static str {
    match name.rsplit('.').next() {
        Some("html") => "text/html; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("js") | Some("mjs") => "text/javascript; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("json") | Some("map") => "application/json",
        Some("png") => "image/png",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        _ => "application/octet-stream",
    }
}

pub fn serve(app: Arc<App>, addr: &str, threads: usize) -> Result<()> {
    let server = Arc::new(Server::http(addr).map_err(|e| anyhow!("cannot listen on {addr}: {e}"))?);
    eprintln!("suyo listening on http://{addr}");
    let mut handles = vec![];
    for _ in 0..threads.max(1) {
        let server = server.clone();
        let app = app.clone();
        handles.push(std::thread::spawn(move || {
            let mut store = match Store::open(&app.db) {
                Ok(s) => s,
                Err(e) => return eprintln!("worker failed to open db: {e:#}"),
            };
            for req in server.incoming_requests() {
                handle(&app, &mut store, req);
            }
        }));
    }
    for h in handles {
        let _ = h.join();
    }
    Ok(())
}

type Resp = Response<std::io::Cursor<Vec<u8>>>;

fn hdr(k: &str, v: &str) -> Header {
    Header::from_bytes(k.as_bytes(), v.as_bytes()).unwrap()
}

fn respond(status: u16, ctype: &str, body: impl Into<Vec<u8>>) -> Resp {
    Response::from_data(body.into())
        .with_status_code(status)
        .with_header(hdr("Content-Type", ctype))
        .with_header(hdr("Access-Control-Allow-Origin", "*"))
        .with_header(hdr("Cache-Control", "no-store"))
}

fn json_resp(status: u16, v: &Value) -> Resp {
    respond(
        status,
        "application/json",
        serde_json::to_vec(v).unwrap_or_default(),
    )
}

fn err(status: u16, msg: impl std::fmt::Display) -> Resp {
    json_resp(status, &json!({ "error": msg.to_string() }))
}

/// Answer one request. Public so a host server can delegate everything under `app.base` to suyo.
pub fn handle(app: &App, store: &mut Store, mut req: Request) {
    let url = req.url().to_string();
    let (path, query) = url.split_once('?').unwrap_or((&url, ""));
    let path = match path.strip_prefix(app.base.as_str()) {
        Some("") => "/".to_string(),
        Some(p) if p.starts_with('/') => p.to_string(),
        _ => {
            let _ = req.respond(err(404, "not found"));
            return;
        }
    };
    let mut params: Vec<(String, String)> = url::form_urlencoded::parse(query.as_bytes())
        .into_owned()
        .collect();
    let method = req.method().clone();
    let mut body = String::new();
    if matches!(method, Method::Post | Method::Put) {
        if req
            .as_reader()
            .take(256 << 20)
            .read_to_string(&mut body)
            .is_err()
        {
            let _ = req.respond(err(400, "body must be UTF-8"));
            return;
        }
        let is_form = req.headers().iter().any(|h| {
            h.field.equiv("Content-Type")
                && h.value
                    .as_str()
                    .starts_with("application/x-www-form-urlencoded")
        });
        if is_form && path == "/render" {
            params.extend(url::form_urlencoded::parse(body.as_bytes()).into_owned());
        }
    }
    let authorized = match &app.write_token {
        None => true,
        Some(t) => {
            req.headers().iter().any(|h| {
                h.field.equiv("Authorization") && h.value.as_str() == format!("Bearer {t}")
            }) || params.iter().any(|(k, v)| k == "token" && v == t)
        }
    };
    let started = std::time::Instant::now();
    let resp = route(
        app,
        store,
        &method,
        &path,
        Params(params),
        &body,
        authorized,
    )
    .unwrap_or_else(|e| err(400, format!("{e:#}")));
    if started.elapsed().as_millis() > 1500 {
        eprintln!(
            "slow request {}ms: {method} {url}",
            started.elapsed().as_millis()
        );
    }
    let _ = req.respond(resp);
}

/// A file of the built UI: from `--assets <dist dir>` on disk when set, else the embedded copy.
fn asset(app: &App, name: &str) -> Option<Resp> {
    if name.contains("..") {
        return None;
    }
    let mut found: Option<(&str, Vec<u8>)> = None;
    if let Some(dir) = &app.assets {
        if let Ok(b) = std::fs::read(dir.join(name)) {
            found = Some((content_type(name), b));
        }
    }
    let (ctype, bytes) = found.or_else(|| embedded(name).map(|(ct, b)| (ct, b.to_vec())))?;
    if name.ends_with(".html") && (!app.base.is_empty() || app.brand.is_some()) {
        let mut html = with_base(&String::from_utf8_lossy(&bytes), &app.base);
        let host = serde_json::json!({"brand": app.brand, "nav": app.nav});
        html = html.replacen(
            "<script>window.SUYO_BASE",
            &format!("<script>window.SUYO_HOST={host};window.SUYO_BASE"),
            1,
        );
        return Some(respond(200, ctype, html));
    }
    Some(respond(200, ctype, bytes))
}

/// The single page of the UI; it routes on the path itself.
fn page(app: &App) -> Resp {
    asset(app, "index.html").unwrap_or_else(|| err(500, "UI missing: index.html"))
}

/// Rewrite a page so it works under a path prefix: asset links get the prefix and the
/// scripts learn it through `window.SUYO_BASE`.
fn with_base(html: &str, base: &str) -> String {
    let js = serde_json::to_string(base).unwrap_or_default();
    html.replace("\"/static/", &format!("\"{base}/static/"))
        .replacen(
            "<script",
            &format!("<script>window.SUYO_BASE={js};</script><script"),
            1,
        )
}

fn route(
    app: &App,
    store: &mut Store,
    method: &Method,
    path: &str,
    p: Params,
    body: &str,
    authorized: bool,
) -> Result<Resp> {
    let write = matches!(method, Method::Post | Method::Put | Method::Delete);
    if write && !authorized && path != "/render" {
        return Ok(err(
            401,
            "write token required (Authorization: Bearer <token>)",
        ));
    }
    Ok(match (method, path) {
        (Method::Get, "/" | "/embed" | "/docs" | "/d" | "/d/") => page(app),
        (Method::Get, p) if p.starts_with("/d/") => page(app),
        (Method::Get, "/favicon.ico") => {
            asset(app, "favicon.svg").unwrap_or_else(|| err(404, "not found"))
        }
        (Method::Get, p) if p.starts_with("/static/") => {
            asset(app, &p[8..]).unwrap_or_else(|| err(404, "not found"))
        }
        (Method::Get, "/api/health") => json_resp(
            200,
            &json!({"ok": true, "version": env!("CARGO_PKG_VERSION")}),
        ),

        (Method::Get | Method::Post, "/render") => render_route(app, store, &p)?,

        (Method::Get, "/metrics/find") => {
            let q = p.get("query").unwrap_or("*");
            json_resp(200, &metrics_find(store, q)?)
        }
        (Method::Get, "/metrics/index.json") => json_resp(
            200,
            &json!(store
                .series()?
                .into_iter()
                .map(|m| m.name)
                .collect::<Vec<_>>()),
        ),
        (Method::Get, "/metrics/expand") => {
            let index = store.series()?;
            let mut out = vec![];
            for q in p.all("query") {
                out.extend(
                    eval::match_paths(q, &index)?
                        .into_iter()
                        .map(|m| m.name.clone()),
                );
            }
            json_resp(200, &json!({ "results": out }))
        }
        (Method::Get, "/api/series") => {
            let index = store.series()?;
            let list = match p.get("query") {
                Some(q) => eval::match_paths(q, &index)?.into_iter().cloned().collect(),
                None => index,
            };
            let counts = p.get("counts").is_some();
            let mut out = vec![];
            for m in list {
                let mut v = serde_json::to_value(&m)?;
                if counts {
                    v["points"] = json!(store.point_count(m.id)?);
                }
                out.push(v);
            }
            json_resp(200, &json!(out))
        }
        (Method::Put | Method::Post, "/api/series/meta") => {
            let v: Value = serde_json::from_str(body)?;
            let name = v["name"].as_str().ok_or_else(|| anyhow!("missing name"))?;
            let hint = MetaHint {
                unit: v["unit"].as_str().map(String::from),
                agg: v["agg"].as_str().map(AggFn::parse).transpose()?,
                interval: v["interval"]
                    .as_str()
                    .map(|s| Span::parse(s).map(|x| x.approx_secs()))
                    .transpose()?,
                description: v["description"].as_str().map(String::from),
            };
            store.set_meta(name, &hint)?;
            json_resp(200, &json!({"ok": true}))
        }
        (Method::Delete, "/api/series") => {
            let name = p.get("name").ok_or_else(|| anyhow!("missing ?name="))?;
            json_resp(200, &json!({"deleted": store.delete_series(name)?}))
        }
        (Method::Post, "/api/ingest") => {
            let (pts, hints) = ingest::parse_json(body, app.zone)?;
            let n = store.write(&pts, &hints)?;
            json_resp(200, &json!({"written": n}))
        }
        (Method::Post, "/api/ingest/plaintext") => {
            let pts = ingest::parse_plaintext(body)?;
            let n = store.write(&pts, &HashMap::new())?;
            json_resp(200, &json!({"written": n}))
        }
        (Method::Get, "/api/functions") => json_resp(200, &json!(catalog::FUNCTIONS)),
        (Method::Get, "/api/dashboards") => {
            let list: Vec<Value> = store
                .dashboards()?
                .into_iter()
                .map(|(name, spec, updated)| {
                    let v: Value = serde_json::from_str(&spec).unwrap_or(Value::Null);
                    json!({"name": name, "title": v["title"], "description": v["description"], "panels": v["panels"].as_array().map(|a| a.len()).unwrap_or(0), "updated": updated})
                })
                .collect();
            json_resp(200, &json!(list))
        }
        (_, p) if p.starts_with("/api/dashboards/") => {
            let name = &p["/api/dashboards/".len()..];
            match method {
                Method::Get => match store.dashboard(name)? {
                    Some(s) => respond(200, "application/json", s),
                    None => err(404, format!("no dashboard '{name}'")),
                },
                Method::Put | Method::Post => {
                    let v: Value = serde_json::from_str(body)
                        .map_err(|e| anyhow!("dashboard must be JSON: {e}"))?;
                    if !v["panels"].is_array() {
                        return Ok(err(400, "dashboard needs a \"panels\" array"));
                    }
                    store.put_dashboard(name, &serde_json::to_string_pretty(&v)?)?;
                    json_resp(200, &json!({"ok": true, "name": name}))
                }
                Method::Delete => {
                    json_resp(200, &json!({"deleted": store.delete_dashboard(name)?}))
                }
                _ => err(405, "method not allowed"),
            }
        }
        _ => err(404, "not found"),
    })
}

fn render_route(app: &App, store: &Store, p: &Params) -> Result<Resp> {
    let format = p.get("format").unwrap_or("json");
    if format == "html" {
        return Ok(page(app));
    }
    let r = render::run(store, p, app.zone)?;
    Ok(match format {
        "json" => {
            if r.series.is_empty() && !r.errors.is_empty() {
                err(400, &r.errors[0].1)
            } else {
                json_resp(200, &render::graphite_json(&r))
            }
        }
        "suyo" => json_resp(200, &render::suyo_json(&r)),
        "csv" => respond(200, "text/csv; charset=utf-8", render::csv(&r)),
        "svg" => respond(200, "image/svg+xml", svg::render(&r, p)),
        o => err(
            400,
            format!("unknown format '{o}' (json, suyo, csv, svg, html)"),
        ),
    })
}

/// Graphite /metrics/find: children of a glob, one level at a time.
fn metrics_find(store: &Store, query: &str) -> Result<Value> {
    let depth = query.split('.').count();
    let index = store.series()?;
    let re = eval::glob_regex(query)?;
    let mut nodes: BTreeMap<String, (bool, bool)> = BTreeMap::new();
    for m in &index {
        let parts: Vec<&str> = m.name.split('.').collect();
        if parts.len() < depth {
            continue;
        }
        let prefix = parts[..depth].join(".");
        if !re.is_match(&prefix) {
            continue;
        }
        let e = nodes.entry(prefix).or_insert((false, false));
        if parts.len() == depth {
            e.0 = true;
        } else {
            e.1 = true;
        }
    }
    Ok(json!(nodes
        .into_iter()
        .map(|(id, (leaf, expandable))| json!({
            "id": id,
            "text": id.rsplit('.').next().unwrap_or(&id),
            "leaf": leaf as i32,
            "expandable": expandable as i32,
            "allowChildren": expandable as i32,
        }))
        .collect::<Vec<_>>()))
}

#[cfg(test)]
mod tests {
    use super::with_base;

    #[test]
    fn base_rewrites_assets_and_injects_prefix() {
        let html = r#"<link rel="stylesheet" href="/static/suyo.css"><script type="module" src="/static/dash.js"></script>"#;
        let out = with_base(html, "/suyo");
        assert!(out.contains(r#"href="/suyo/static/suyo.css""#));
        assert!(out.contains(r#"src="/suyo/static/dash.js""#));
        assert!(out.contains(r#"window.SUYO_BASE="/suyo""#));
    }

    #[test]
    fn base_injected_before_the_built_bundle() {
        // shape of ui/dist/index.html as written by Vite (base "/static/")
        let html = r#"<head><link rel="icon" href="/static/favicon.svg"><script>/*theme*/</script><script type="module" crossorigin src="/static/assets/suyo.js"></script><link rel="stylesheet" crossorigin href="/static/assets/style.css"></head>"#;
        let out = with_base(html, "/suyo");
        let base_at = out.find("window.SUYO_BASE").unwrap();
        assert!(base_at < out.find("/suyo/static/assets/suyo.js").unwrap());
        assert!(out.contains(r#"href="/suyo/static/assets/style.css""#));
        assert!(out.contains(r#"href="/suyo/static/favicon.svg""#));
    }
}
