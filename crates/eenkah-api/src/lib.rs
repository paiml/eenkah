//! eenkah-api: the HTTP API and the embedded React app (`ui/`, built into `ui/dist`).
//! suyo is mounted under `/suyo` for its render API and dashboards, so every chart is a suyo
//! dashboard the athlete can copy and edit. Binds to 127.0.0.1 unless told otherwise (PRV-1).

pub mod jobs;
pub mod views;

use anyhow::{anyhow, Result};
use eenkah_store::{DataDir, Db};
use serde_json::Value;
use std::io::Read;
use std::sync::Arc;
use tiny_http::{Header, Method, Request, Response, Server};

mod ui {
    include!(concat!(env!("OUT_DIR"), "/ui_assets.rs"));
}

/// Default dashboards, restored by name (CUS-2). Editing or deleting one never breaks an upgrade.
pub const DASHBOARDS: &[(&str, &str)] = &[
    ("today", include_str!("../../../dashboards/today.json")),
    ("week", include_str!("../../../dashboards/week.json")),
    ("trends", include_str!("../../../dashboards/trends.json")),
    ("model", include_str!("../../../dashboards/model.json")),
];

/// PRV-1: loopback only unless the athlete passes another address.
pub const DEFAULT_LISTEN: &str = "127.0.0.1:8090";

/// docs/METRICS.md, generated from the catalogue (MET-4).
pub fn metrics_markdown() -> String {
    let mut s = String::from("# Metric catalogue\n\nGenerated by `eenkah metrics --markdown` from `eenkah-core/src/catalog.rs`. Do not edit by hand.\nWorked examples checked by hand live in the unit tests named `*_by_hand` in `eenkah-core`.\n\n| Series | Unit | What | Formula | Source |\n|---|---|---|---|---|\n");
    for m in eenkah_core::catalog::METRICS {
        s += &format!(
            "| `{}` | {} | {}{} | {} | {} |\n",
            m.series,
            m.unit,
            m.label,
            if m.why.is_empty() { String::new() } else { format!(": {}", m.why) },
            m.formula.replace('|', "\\|"),
            m.source
        );
    }
    s
}

pub const NAV: &[(&str, &str)] = &[
    ("Today", "/"),
    ("Week", "/week"),
    ("Trends", "/trends"),
    ("Activities", "/activities"),
    ("Model", "/model"),
    ("Data", "/data"),
];

/// Add any default dashboard that is missing. `force` restores the named ones to default.
pub fn seed_dashboards(db: &Db, force: &[&str]) -> Result<Vec<String>> {
    let store = db.suyo()?;
    let mut done = vec![];
    for (name, spec) in DASHBOARDS {
        if force.contains(name) || store.dashboard(name)?.is_none() {
            store.put_dashboard(name, spec)?;
            done.push(name.to_string());
        }
    }
    Ok(done)
}

pub struct ServeOpts {
    pub listen: String,
    pub threads: usize,
    /// Serve the React app from this directory instead of the embedded copy (development).
    pub assets: Option<std::path::PathBuf>,
}

struct Ctx {
    dir: DataDir,
    job: jobs::Job,
    assets: Option<std::path::PathBuf>,
}

pub fn serve(dir: DataDir, opts: ServeOpts) -> Result<()> {
    let db = Db::open(&dir)?;
    seed_dashboards(&db, &[])?;
    let suyo_app = Arc::new(suyo::server::App {
        db: dir.db_path().to_string_lossy().to_string(),
        zone: suyo::timeutil::Zone::Named(db.tz()),
        assets: std::env::var("EENKAH_SUYO_ASSETS").ok().map(Into::into),
        write_token: None,
        base: "/suyo".into(),
        brand: Some(("eenkah".into(), "/".into())),
        nav: NAV.iter().map(|(a, b)| (a.to_string(), b.to_string())).collect(),
    });
    drop(db);
    let ctx = Arc::new(Ctx {
        dir: dir.clone(),
        job: Default::default(),
        assets: opts.assets,
    });
    let server = Arc::new(Server::http(&opts.listen).map_err(|e| anyhow!("cannot listen on {}: {e}", opts.listen))?);
    eprintln!("eenkah on http://{}/  (data: {})", opts.listen, dir.root.display());
    if !ui::BUILT {
        eprintln!("warning: the web UI was not built into this binary; run `make build`");
    }
    let mut handles = vec![];
    for _ in 0..opts.threads.max(1) {
        let (server, ctx, suyo_app) = (server.clone(), ctx.clone(), suyo_app.clone());
        handles.push(std::thread::spawn(move || {
            let (mut db, mut store) = match (Db::open(&ctx.dir), suyo::store::Store::open(&suyo_app.db)) {
                (Ok(d), Ok(s)) => (d, s),
                (Err(e), _) | (_, Err(e)) => return eprintln!("worker failed to open database: {e:#}"),
            };
            for req in server.incoming_requests() {
                if req.url() == "/suyo" || req.url().starts_with("/suyo/") || req.url().starts_with("/suyo?") {
                    suyo::server::handle(&suyo_app, &mut store, req);
                } else {
                    handle(&ctx, &mut db, req);
                }
            }
        }));
    }
    for h in handles {
        let _ = h.join();
    }
    Ok(())
}

type Resp = Response<std::io::Cursor<Vec<u8>>>;

fn respond(status: u16, ctype: &str, body: impl Into<Vec<u8>>) -> Resp {
    Response::from_data(body.into())
        .with_status_code(status)
        .with_header(Header::from_bytes("Content-Type", ctype).unwrap())
        .with_header(Header::from_bytes("Cache-Control", "no-store").unwrap())
}

fn json(v: &Value) -> Resp {
    respond(200, "application/json", serde_json::to_vec_pretty(v).unwrap_or_default())
}

fn bad(msg: impl std::fmt::Display) -> Resp {
    respond(400, "application/json", serde_json::json!({"error": msg.to_string()}).to_string())
}

fn content_type(name: &str) -> &'static str {
    match name.rsplit('.').next() {
        Some("html") => "text/html; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("js") => "text/javascript; charset=utf-8",
        Some("svg") => "image/svg+xml",
        Some("json") => "application/json",
        Some("png") => "image/png",
        Some("woff2") => "font/woff2",
        _ => "application/octet-stream",
    }
}

/// A file of the React app: from `--assets` when developing, else embedded at build time.
fn asset(ctx: &Ctx, name: &str) -> Option<Resp> {
    if name.contains("..") {
        return None;
    }
    if let Some(dir) = &ctx.assets {
        if let Ok(b) = std::fs::read(dir.join(name)) {
            return Some(respond(200, content_type(name), b));
        }
    }
    ui::file(name).map(|b| {
        let r = respond(200, content_type(name), b.to_vec());
        // hashed asset names never change content, so they may be cached for good
        if name.starts_with("assets/") {
            r.with_header(Header::from_bytes("Cache-Control", "public, max-age=31536000, immutable").unwrap())
        } else {
            r
        }
    })
}

fn handle(ctx: &Ctx, db: &mut Db, mut req: Request) {
    let url = req.url().to_string();
    let (path, query) = url.split_once('?').unwrap_or((&url, ""));
    let q: Vec<(String, String)> = url::form_urlencoded::parse(query.as_bytes()).into_owned().collect();
    let get = |k: &str| q.iter().find(|(a, _)| a == k).map(|(_, b)| b.as_str());
    let mut body = String::new();
    if matches!(req.method(), Method::Post | Method::Put) && req.as_reader().take(1 << 20).read_to_string(&mut body).is_err() {
        let _ = req.respond(bad("body must be UTF-8"));
        return;
    }
    let method = req.method().clone();
    let resp: Result<Resp> = match (&method, path) {
        (Method::Get, "/api/brief") => views::brief_text(db).map(|t| respond(200, "text/plain; charset=utf-8", t)),
        (Method::Get, "/api/today") => views::today(db).map(|v| json(&v)),
        (Method::Get, "/api/week") => views::week(db).map(|v| json(&v)),
        (Method::Get, "/api/activities") => views::activities(
            db,
            get("since").and_then(|s| chrono::NaiveDate::parse_from_str(s, "%Y-%m-%d").ok()),
            get("limit").and_then(|l| l.parse().ok()).unwrap_or(50),
        )
        .map(|v| json(&v)),
        (Method::Get, p) if p.starts_with("/api/activities/") => match p["/api/activities/".len()..].parse::<i64>() {
            Ok(id) => views::activity(db, id).map(|v| v.map(|v| json(&v)).unwrap_or_else(|| respond(404, "application/json", r#"{"error":"no such activity"}"#))),
            Err(_) => Ok(bad("activity id must be a number")),
        },
        (Method::Get, "/api/personal") => views::personal(db).map(|v| json(&v)),
        (Method::Post, p) if p.starts_with("/api/activities/") && p.ends_with("/type") => (|| {
            let Ok(id) = p["/api/activities/".len()..p.len() - "/type".len()].parse::<i64>() else {
                return Ok(bad("activity id must be a number"));
            };
            let v: Value = serde_json::from_str(&body)?;
            if let Err(e) = eenkah_learn::personal::set_label(db, id, v["label"].as_str()) {
                return Ok(bad(format!("{e:#}")));
            }
            views::activity(db, id).map(|v| v.map(|v| json(&v)).unwrap_or_else(|| respond(404, "application/json", r#"{"error":"no such activity"}"#)))
        })(),
        (Method::Get, "/api/model") => eenkah_learn::model_text(db).map(|t| respond(200, "text/plain; charset=utf-8", t)),
        (Method::Get, "/api/forecast") => eenkah_learn::model_summary(db).map(|v| json(&v)),
        (Method::Get, "/api/metrics") => Ok(json(&views::metric_catalog())),
        (Method::Get, "/api/status") => views::status(db, jobs::signed_in(&ctx.dir)).map(|v| json(&v)),
        (Method::Get, "/api/marks") => views::marks(db).map(|v| json(&v)),
        (Method::Post, "/api/marks") => (|| {
            let v: Value = serde_json::from_str(&body)?;
            let day = chrono::NaiveDate::parse_from_str(v["day"].as_str().unwrap_or(""), "%Y-%m-%d").map_err(|_| anyhow!("day must be YYYY-MM-DD"))?;
            let kind = v["kind"].as_str().filter(|k| !k.trim().is_empty()).ok_or_else(|| anyhow!("kind is required"))?;
            db.put_mark(day, kind.trim(), v["value"].as_f64().unwrap_or(1.0), v["note"].as_str().unwrap_or(""))?;
            eenkah_store::derive::run(db)?;
            views::marks(db).map(|v| json(&v))
        })(),
        (Method::Delete, "/api/marks") => (|| {
            let (Some(day), Some(kind)) = (get("day"), get("kind")) else {
                return Ok(bad("day and kind are required"));
            };
            db.conn.execute("DELETE FROM mark WHERE day=?1 AND kind=?2", (day, kind))?;
            eenkah_store::derive::run(db)?;
            views::marks(db).map(|v| json(&v))
        })(),
        (Method::Get, "/api/import") => Ok(json(&serde_json::to_value(&*ctx.job.lock().unwrap()).unwrap_or_default())),
        (Method::Post, "/api/import") => {
            let since = serde_json::from_str::<Value>(&body)
                .ok()
                .and_then(|v| v["since"].as_str().and_then(|s| chrono::NaiveDate::parse_from_str(s, "%Y-%m-%d").ok()));
            if !jobs::signed_in(&ctx.dir) {
                Ok(respond(409, "application/json", r#"{"error":"not signed in to Garmin Connect: run `eenkah login` once"}"#))
            } else if jobs::start(&ctx.job, ctx.dir.clone(), jobs::ImportOpts { since, ..Default::default() }) {
                Ok(json(&serde_json::json!({"started": true})))
            } else {
                Ok(respond(409, "application/json", r#"{"error":"an import is already running"}"#))
            }
        }
        (Method::Post, "/api/train") => match jobs::retrain_unless_running(&ctx.job, db) {
            Ok(v) => Ok(json(&v)),
            Err(e) if ctx.job.lock().unwrap().running => Ok(respond(409, "application/json", serde_json::json!({"error": format!("{e:#}")}).to_string())),
            Err(e) => Err(e),
        },
        (Method::Get, "/api/reset") => jobs::reset_preview(db, false).map(|v| json(&serde_json::to_value(v).unwrap_or_default())),
        (Method::Post, "/api/reset") => {
            if serde_json::from_str::<Value>(&body).ok().and_then(|v| v["confirm"].as_bool()) != Some(true) {
                Ok(bad("send {\"confirm\": true} to delete the downloaded data"))
            } else {
                match jobs::reset_unless_running(&ctx.job, db) {
                    Ok(r) => Ok(json(&serde_json::json!({"removed": r}))),
                    Err(e) => Ok(respond(409, "application/json", serde_json::json!({"error": format!("{e:#}")}).to_string())),
                }
            }
        }
        (Method::Get, "/api/health") => Ok(json(&serde_json::json!({"ok": true, "version": env!("CARGO_PKG_VERSION")}))),
        (_, p) if p.starts_with("/api/") => Ok(respond(404, "application/json", r#"{"error":"not found"}"#)),
        (Method::Get, p) if p.starts_with("/assets/") || p == "/favicon.svg" => Ok(asset(ctx, &p[1..]).unwrap_or_else(|| respond(404, "text/plain", "not found"))),
        // every other GET is a page of the single-page app
        (Method::Get, _) => Ok(asset(ctx, "index.html").unwrap_or_else(|| respond(500, "text/plain", "UI missing"))),
        _ => Ok(respond(405, "application/json", r#"{"error":"method not allowed"}"#)),
    };
    let resp = resp.unwrap_or_else(|e| respond(500, "application/json", serde_json::json!({"error": format!("{e:#}")}).to_string()));
    let _ = req.respond(resp);
}
